#!/usr/bin/env node
/**
 * Refresh the Chinese IPv4 ranges embedded in the Chrome extension.
 *
 * The runtime extension must not download routing rules: that would add a
 * third-party startup request and make a user's route depend on a live remote
 * service. This tool fetches a reviewed, MIT-licensed source during release,
 * validates it, merges adjacent ranges, and writes a deterministic module.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://chnroutes2.cdn.skk.moe/chnroutes.txt";
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(ROOT, "extension", "src", "china-ipv4-ranges.js");
const CIDR = /^(\d{1,3}(?:\.\d{1,3}){3})\/(\d|[12]\d|3[0-2])$/;

function ipv4ToNumber(address) {
  const octets = address.split(".").map(Number);
  if (octets.length !== 4 || octets.some((octet) => !Number.isInteger(octet) || octet < 0 || octet > 255)) {
    throw new Error(`Invalid IPv4 address: ${address}`);
  }
  return (((octets[0] * 256 + octets[1]) * 256 + octets[2]) * 256 + octets[3]);
}

function parseAndMerge(text) {
  const ranges = [];
  for (const raw of text.split(/\r?\n/)) {
    const match = raw.trim().match(CIDR);
    if (!match) continue;
    const start = ipv4ToNumber(match[1]);
    const prefix = Number(match[2]);
    const size = 2 ** (32 - prefix);
    ranges.push([start, start + size - 1]);
  }
  if (ranges.length < 1000) throw new Error(`Source has too few IPv4 CIDRs: ${ranges.length}`);
  ranges.sort((left, right) => left[0] - right[0] || left[1] - right[1]);
  const merged = [];
  for (const range of ranges) {
    const previous = merged.at(-1);
    if (previous && range[0] <= previous[1] + 1) previous[1] = Math.max(previous[1], range[1]);
    else merged.push([...range]);
  }
  return { cidrCount: ranges.length, ranges: merged };
}

const response = await fetch(SOURCE_URL, { headers: { "user-agent": "Browser-Gateway route updater" } });
if (!response.ok) throw new Error(`Unable to download China route source: HTTP ${response.status}`);
const { cidrCount, ranges } = parseAndMerge(await response.text());
const generated = `// Generated by tools/update-china-routes.mjs; do not edit manually.\n// Source: ${SOURCE_URL} (MIT license), ${cidrCount} CIDRs merged into ${ranges.length} ranges.\n// The list is intentionally committed so Chrome never downloads routing rules at runtime.\nexport const CHINA_IPV4_RANGES = Object.freeze(${JSON.stringify(ranges)});\n`;
await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, generated, "utf8");
console.log(`Wrote ${ranges.length} merged Chinese IPv4 ranges to ${OUTPUT}`);
